/**
 * Regenerate plugin/ov-tools.schema.json from the live OpenViking MCP server.
 *
 * The native MiMo tool definitions are data, not code: `plugin/tools.js` builds
 * its zod arg shapes and its `tools/call` dispatch straight out of the JSON this
 * script writes, so a schema drift between OV releases shows up as a reviewable
 * diff instead of a silently wrong tool signature.
 *
 * Usage (no system node on this machine; use MiMo's bundled Electron):
 *   ELECTRON_RUN_AS_NODE=1 "C:/Program Files/Xiaomi MiMo/Xiaomi MiMo.exe" \
 *     scripts/capture-tool-schemas.mjs [--out plugin/ov-tools.schema.json]
 *
 * Credentials come from the vendored shared credentials module, which reads
 * ~/.openviking/ovcli.conf (or the OPENVIKING_* overrides) exactly like the
 * plugin does at runtime.
 */

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { resolveOpenVikingCredentials } from "../lib/credentials.mjs";
import { openMcpSession } from "../plugin/mcp-client.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, "..");
const DEFAULT_OUT = resolve(REPO_ROOT, "plugin", "ov-tools.schema.json");

function parseArgs(argv) {
  const out = { out: DEFAULT_OUT };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--out" && argv[i + 1]) {
      out.out = resolve(argv[++i]);
    }
  }
  return out;
}

async function main() {
  const { out } = parseArgs(process.argv.slice(2));
  const cfg = resolveOpenVikingCredentials();
  if (!cfg.mcpUrl) throw new Error("no OpenViking MCP URL resolved");

  const session = await openMcpSession(cfg);
  if (!session.ok) throw new Error(`MCP initialize failed: ${session.error}`);
  try {
    const listed = await session.listTools();
    if (!listed.ok) throw new Error(`MCP tools/list failed: ${listed.error}`);
    const tools = listed.tools;
    if (!Array.isArray(tools) || tools.length === 0) {
      throw new Error("tools/list returned no tools");
    }
    const payload = {
      $comment: [
        "Generated by scripts/capture-tool-schemas.mjs — do not hand-edit.",
        "Source: POST <OV>/mcp {\"method\":\"tools/list\"} (JSON-RPC 2.0 over streamable HTTP).",
        "Each entry keeps the server's inputSchema verbatim; plugin/tools.js converts",
        "it to a zod raw shape for @mimo-ai/plugin's tool() at load time.",
      ].join(" "),
      mcpUrl: cfg.mcpUrl,
      protocolVersion: session.protocolVersion,
      capturedAt: new Date().toISOString(),
      toolCount: tools.length,
      tools: tools.map((tool) => ({
        name: tool.name,
        title: tool.title,
        description: tool.description,
        inputSchema: tool.inputSchema,
      })),
    };
    await mkdir(dirname(out), { recursive: true });
    await writeFile(out, `${JSON.stringify(payload, null, 2)}\n`, "utf8");
    process.stdout.write(
      `captured ${payload.toolCount} tools from ${payload.mcpUrl} -> ${out}\n`
      + `${payload.tools.map((t) => t.name).join(", ")}\n`,
    );
  } finally {
    await session.close();
  }
}

/** Exercise one tool end-to-end; used by the verify harness as a live smoke test. */
export async function probeTool(name, args) {
  const cfg = resolveOpenVikingCredentials();
  const session = await openMcpSession(cfg);
  try {
    const res = await session.callTool(name, args);
    return res.ok ? { ok: true, result: res.result } : { ok: false, error: res.error };
  } finally {
    await session.close();
  }
}

const invokedDirectly = process.argv[1]
  && resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase();

if (invokedDirectly) {
  main().catch((error) => {
    process.stderr.write(`${error?.stack || error}\n`);
    process.exitCode = 1;
  });
}
